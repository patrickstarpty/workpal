import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import path from 'node:path';
import {withBrowser, signIn} from './browser-fixture.mjs';

await withBrowser(async ({base, newPage, repo, expect}) => {
  const page = await newPage();
  await signIn(page, base);
  await page.getByLabel('Workspace', {exact:true}).selectOption('1');
  await page.getByRole('button', {name:'Projects', exact:true}).click();
  await expect(page.getByRole('heading', {name:'Projects', exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Create project'}).click();
  await page.getByLabel('Project name').fill('Project <img src=x>');
  await page.getByLabel('Description', {exact:true}).fill('Actual description');
  await page.getByRole('button', {name:'Save', exact:true}).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.getByRole('heading', {name:'Project <img src=x>', exact:true})).toBeVisible();
  assert.equal(await page.locator('main img').count(), 0);
  const fresh = await newPage();
  await signIn(fresh, base);
  await fresh.getByLabel('Workspace', {exact:true}).selectOption('1');
  await fresh.getByRole('button', {name:'Projects', exact:true}).click();
  await fresh.getByRole('button', {name:/^Project <img src=x> \(#/}).click();
  await expect(fresh.getByRole('heading', {name:'Project <img src=x>', exact:true})).toBeVisible();
  await fresh.reload();
  await fresh.getByLabel('Workspace', {exact:true}).selectOption('1');
  await fresh.getByRole('button', {name:'Projects', exact:true}).click();
  await expect(fresh.locator('.project-row')).toContainText(['Actual description']);
  await fresh.context().close();
  const edit = page.getByRole('button', {name:'Edit project'});
  await edit.focus(); await page.keyboard.press('Enter');
  await expect(page.getByLabel('Project name')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByLabel('Description', {exact:true})).toBeFocused();
  await page.keyboard.press('Escape'); await expect(edit).toBeFocused();
  await edit.click(); await page.getByLabel('Project name').fill('Edited project');
  await page.getByRole('button', {name:'Save', exact:true}).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.getByRole('heading', {name:'Edited project', exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Archive project'}).click();
  await page.getByRole('button', {name:'Archive', exact:true}).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.getByText('No projects found.', {exact:true})).toBeVisible();
  await page.getByLabel('Include archived').check();
  await page.getByRole('button', {name:/Edited project \(#/}).click();
  await page.getByRole('button', {name:'Restore project'}).click();
  await page.getByRole('button', {name:'Restore', exact:true}).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', {name:'Archive project', exact:true})).toBeVisible();
  await expect(page.locator('.project-row')).toContainText(['Active']);
  const output = path.join(repo, 'outputs/workpal-web'); await mkdir(output, {recursive:true});
  await page.evaluate(() => scrollTo(0, 0));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:path.join(output, 'a53-projects-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:path.join(output, 'a53-projects-mobile.png')});
  console.log('projects: creation, reload/new-context persistence, editing, archive/restore, keyboard and 1440/390 layout passed');
});
