import {mkdir} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {withBrowser, signIn} from './browser-fixture.mjs';

if (process.argv.slice(2).join(' ') !== '--suite shell') throw Error('Supported suite: shell');
await withBrowser(async ({base, newPage, repo, expect}) => {
  const page = await newPage();
  await signIn(page, base);
  await page.getByLabel('Workspace', {exact:true}).selectOption('1');
  await expect(page.getByRole('heading', {name:'First', exact:true})).toBeVisible();
  const edit = page.getByRole('button', {name:'Edit workspace'});
  await edit.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog', {name:'Edit workspace'})).toBeVisible();
  await expect(page.getByLabel('Workspace name')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', {name:'Save', exact:true})).toBeFocused();
  await page.keyboard.press('Escape'); await expect(edit).toBeFocused();
  await edit.click();
  const name = '<img src=x onerror=alert(1)> ' + 'Long workspace '.repeat(8);
  await page.getByLabel('Workspace name').fill(name);
  await page.getByLabel('Workspace name').press('Enter');
  await expect(page.getByRole('heading', {name, exact:true})).toBeVisible();
  await expect(page.locator('select option:checked')).toContainText(name.trim());
  await page.reload();
  await page.getByLabel('Workspace', {exact:true}).selectOption('1');
  await expect(page.getByRole('heading', {name, exact:true})).toBeVisible();
  assert.equal(await page.locator('main img').count(), 0);
  const outputs = path.join(repo, 'outputs/workpal-web'); await mkdir(outputs, {recursive:true});
  await page.screenshot({path:path.join(outputs, 'a52-shell-desktop.png')});
  await page.setViewportSize({width:390, height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:path.join(outputs, 'a52-shell-mobile.png')});
  await edit.click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.keyboard.press('Escape'); await expect(edit).toBeFocused();
  await page.getByLabel('Workspace', {exact:true}).selectOption('2');
  await expect(page.getByRole('heading', {name:'Second', exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Sign out'}).click();
  await page.getByLabel('Username').fill('reader');
  await page.getByLabel('Password').fill('qa-password');
  await page.getByRole('button', {name:'Sign in', exact:true}).click();
  await page.getByLabel('Workspace', {exact:true}).selectOption('1');
  await expect(page.getByRole('heading', {name, exact:true})).toBeVisible();
  await expect(page.getByRole('button', {name:'Edit workspace'})).toHaveCount(0);
  const fresh = await newPage(); await signIn(fresh, base);
  await fresh.getByLabel('Workspace', {exact:true}).selectOption('1');
  await expect(fresh.getByRole('heading', {name, exact:true})).toBeVisible();
  console.log('shell: real login, rename, reload/new-context persistence, selection, logout, member permissions and responsive keyboard checks passed');
});
